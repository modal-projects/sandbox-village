"""The TV in the robot's house, and the games console behind it.

The game on the TV is Cold Start Chase, a maze game. Three things about it are real:

- Every maze is generated by a program running in the villager's sandbox, not in the browser.
- Where sidecars are available, that program runs in a *sidecar*: a second container, named
  `console`, started beside the sandbox's main container and reached from it by name over the
  sandbox's private network (`http://console:8765/new`). Offline, or if the sidecar cannot be
  started, the main container draws the maze itself and says so.
- The best score is a file in the villager's home (`games/scores.json`), so it is in the snapshot
  and survives the house going to sleep.

The chase itself is drawn in the browser (static/js/chase.js): a command round trip to a sandbox
takes a third of a second, which is too slow for a game played in real time.
"""

from __future__ import annotations

import json
import re
import time

from .homes import HomeError, Homes

GAME_PATH = "games/tv.py"
CONSOLE = "console"  # the sidecar's name, which is also its hostname inside the sandbox
CONSOLE_PORT = 8765
_MOVE = re.compile(r"new|look|score:(\d{1,7})")

GAME_SOURCE = f'''"""Cold Start Chase: the program behind the TV.

    python3 games/tv.py new          a fresh maze (from the console next door if it answers) and the scores
    python3 games/tv.py score 1230   record a finished game
    python3 games/tv.py look         the scores
    python3 games/tv.py serve        be the console: answer GET /new with a maze, on port {CONSOLE_PORT}

A maze is {{"grid": [...]}}: rows of text, # wall, . request to collect, S snapshot crystal,
C where a cold start begins, P where the player begins.
"""
import json
import random
import sys

W, H = 15, 11


def maze(seed):
    rng = random.Random(seed)
    grid = [["#"] * W for _ in range(H)]
    grid[5][7] = "."
    seen, stack = {{(7, 5)}}, [(7, 5)]
    while stack:  # carve passages between the rooms at odd coordinates
        x, y = stack[-1]
        ways = [(dx, dy) for dx, dy in ((2, 0), (-2, 0), (0, 2), (0, -2)) if 0 < x + dx < W - 1 and 0 < y + dy < H - 1 and (x + dx, y + dy) not in seen]
        if not ways:
            stack.pop()
            continue
        dx, dy = rng.choice(ways)
        grid[y + dy // 2][x + dx // 2] = "."
        grid[y + dy][x + dx] = "."
        seen.add((x + dx, y + dy))
        stack.append((x + dx, y + dy))
    # knock through more walls, so there is always another way round
    walls = [(x, y) for y in range(1, H - 1) for x in range(1, W - 1) if grid[y][x] == "#" and (x + y) % 2 == 1]
    for x, y in rng.sample(walls, min(14, len(walls))):
        grid[y][x] = "."
    corners = [(1, 1), (W - 2, 1), (1, H - 2), (W - 2, H - 2)]
    rng.shuffle(corners)
    for x, y in corners[:3]:
        grid[y][x] = "C"
    grid[corners[3][1]][corners[3][0]] = "S"
    far = [(x, y) for y in range(1, H, 2) for x in range(1, W, 2) if grid[y][x] == "." and abs(x - 7) + abs(y - 5) >= 6]
    x, y = rng.choice(far)
    grid[y][x] = "S"
    grid[5][7] = "P"
    return ["".join(row) for row in grid]


def fresh(by):
    seed = random.randrange(100000)
    return {{"grid": maze(seed), "seed": seed, "by": by}}


def serve():
    import http.server

    class Console(http.server.BaseHTTPRequestHandler):
        def do_GET(self):
            body = json.dumps(fresh("console")).encode()
            self.send_response(200)
            self.send_header("content-type", "application/json")
            self.end_headers()
            self.wfile.write(body)

        def log_message(self, *args):
            pass

    http.server.HTTPServer(("0.0.0.0", {CONSOLE_PORT}), Console).serve_forever()


def scores():
    import pathlib

    path = pathlib.Path(__file__).with_name("scores.json")
    try:
        return path, json.loads(path.read_text())
    except (OSError, ValueError):
        return path, {{"best": 0, "plays": 0, "last": 0}}


def main(args):
    mode = args[0] if args else "look"
    if mode == "serve":
        return serve()
    path, kept = scores()
    out = dict(kept)
    if mode == "new":
        try:
            import urllib.request

            out.update(json.loads(urllib.request.urlopen("http://{CONSOLE}:{CONSOLE_PORT}/new", timeout=1.5).read()))
        except Exception:
            out.update(fresh("main"))  # no console next door: draw it here
    elif mode == "score":
        points = max(0, int(args[1]))
        kept.update(best=max(kept["best"], points), plays=kept["plays"] + 1, last=points)
        path.write_text(json.dumps(kept))
        out = dict(kept)
    print(json.dumps(out))


main(sys.argv[1:])
'''


def play(homes: Homes, vid: str, move: str) -> dict:
    """One request to the TV: `new` (a fresh maze), `score:<points>` (a game ended) or `look`.
    Runs in `vid`'s sandbox and reports the command, how long it took and who drew the maze."""
    move = str(move).strip().lower()
    found = _MOVE.fullmatch(move)
    if not found:
        raise HomeError("The TV only understands new, look, or score:<points>.")
    args = f"score {found.group(1)}" if found.group(1) else move
    command = f"python3 {GAME_PATH} {args}"
    # Switch the console on (once per sandbox): a sidecar container running this same program.
    console = move == "new" and homes.sidecar(vid, CONSOLE, ("python3", "-c", GAME_SOURCE, "serve"))

    def run() -> tuple[dict, int]:
        started = time.monotonic()
        result = homes.exec(vid, command, timeout=15)
        if result.rc != 0:
            # first time anyone has played here (or the program was deleted): put it on the shelf
            homes.write_file(vid, GAME_PATH, GAME_SOURCE)
            started = time.monotonic()
            result = homes.exec(vid, command, timeout=15)
        took = int((time.monotonic() - started) * 1000)
        try:
            return json.loads(result.output.strip().splitlines()[-1]), took
        except (ValueError, IndexError):
            raise HomeError(f"The TV did not answer: {result.output.strip()[:160] or 'nothing came back'}") from None

    state, took = run()
    for _ in range(4):  # a console that was only just switched on may need a moment to answer
        if not console or state.get("by") == "console":
            break
        time.sleep(0.5)
        state, took = run()
    homes.touch(vid)
    return {**state, "ms": took, "command": command, "runtime": homes.runtime_of(vid), "sidecar": bool(console) and state.get("by") == "console"}
